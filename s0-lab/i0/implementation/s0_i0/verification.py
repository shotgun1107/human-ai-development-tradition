"""Technical public-fixture verification record; this is not an S0 run."""

from __future__ import annotations

import platform
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path
from typing import Any

from .error_reporting import safe_exception_message
from .integrity import BUNDLE_RELATIVE, SCHEMA_INSTANCE_MAP, SCHEMA_RELATIVE, sha256_bytes, verify_public_bundle
from .json_validation import load_json
from .schema_suite import audit_broader_upstream_id_impact, validate_public_schema_instances
from .transform import PROFILES, transform_canonical


def _now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def build_public_verification_record(workspace_root: Path) -> dict[str, Any]:
    started = _now()
    errors: list[dict[str, str]] = []
    inputs: list[dict[str, Any]] = []
    outputs: list[dict[str, Any]] = []
    try:
        bundle = workspace_root / BUNDLE_RELATIVE
        manifest_raw = (bundle / "bundle-files.sha256").read_bytes()
        inputs.append({"path": (BUNDLE_RELATIVE / "bundle-files.sha256").as_posix(), "sha256": sha256_bytes(manifest_raw), "bytes": len(manifest_raw)})
        for schema_rel, _ in SCHEMA_INSTANCE_MAP:
            raw = (workspace_root / SCHEMA_RELATIVE / schema_rel).read_bytes()
            inputs.append({"path": (SCHEMA_RELATIVE / schema_rel).as_posix(), "sha256": sha256_bytes(raw), "bytes": len(raw)})

        integrity = verify_public_bundle(workspace_root)
        schemas = validate_public_schema_instances(workspace_root)
        broader_impact = audit_broader_upstream_id_impact(workspace_root)
        if schemas["error_count"]:
            errors.append({"category": "schema", "message": f'{schemas["error_count"]} designated instance errors'})

        for block, suffix in (("BLK-PRACTICE0001", "B1MOSS001"), ("BLK-PRACTICE0002", "B2EMBER001")):
            canonical_path = bundle / "blocks" / block / "canonical-input.json"
            canonical, canonical_raw = load_json(canonical_path)
            inputs.append({"path": canonical_path.relative_to(workspace_root).as_posix(), "sha256": sha256_bytes(canonical_raw), "bytes": len(canonical_raw)})
            for profile in sorted(PROFILES):
                generated = transform_canonical(canonical, profile)
                expected_path = bundle / "packages" / f"{profile}{suffix}" / "input.json"
                expected = expected_path.read_bytes()
                if generated != expected:
                    errors.append({"category": "transformation", "message": f"generated bytes differ: {profile}/{block}"})
                outputs.append({"path": expected_path.relative_to(workspace_root).as_posix(), "sha256": sha256_bytes(generated), "bytes": len(generated)})
    except Exception as exc:  # the record must retain technical failure details
        integrity = None
        schemas = None
        broader_impact = None
        errors.append(
            {"category": type(exc).__name__, "message": safe_exception_message(exc)}
        )

    return {
        "record_kind": "i0-public-technical-verification",
        "not_an_s0_run": True,
        "started_at": started,
        "ended_at": _now(),
        "status": "pass" if not errors else "fail",
        "runtime": {"python": platform.python_version(), "jsonschema": version("jsonschema")},
        "inputs": sorted(inputs, key=lambda item: item["path"]),
        "outputs": sorted(outputs, key=lambda item: item["path"]),
        "integrity_summary": integrity,
        "schema_summary": schemas,
        "broader_upstream_impact": broader_impact,
        "errors": errors,
    }
